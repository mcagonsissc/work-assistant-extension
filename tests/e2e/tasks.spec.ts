test('plans real tasks around meetings, previews overflow, and restores focus after reload', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-12T08:00:00Z') });
  await page.goto('/');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByLabel('Timezone', { exact: true }).fill('UTC');
  await page.getByRole('button', { name: 'Save workday settings' }).click();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  for (const [title, minutes] of [['Write feature', '180'], ['Write docs', '300']]) {
    await page.getByRole('button', { name: 'Add task', exact: true }).click();
    await page.getByLabel('Task title').fill(title);
    await page.getByLabel('Estimate · minutes').fill(minutes);
    await page.getByRole('button', { name: 'Save task', exact: true }).click();
  }
  await page.getByRole('button', { name: 'Add meeting', exact: true }).click();
  await page.getByLabel('Meeting title').fill('Standup');
  await page.getByLabel('Meeting starts').fill('2026-11-12T10:00');
  await page.getByLabel('Meeting ends').fill('2026-11-12T11:00');
  await page.getByRole('button', { name: 'Save meeting', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Proposed schedule' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Doesn’t fit in this workday' })).toBeVisible();
  await expect(page.locator('.overflow')).toContainText('90 min');
  await expect(page.getByRole('list', { name: 'Approved schedule' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Approve plan', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Approved schedule' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('list', { name: 'Approved schedule' })).toBeVisible();
  await expect(page.locator('.timeline-entry.meeting')).toContainText('Standup');
  await expect(page.locator('.timeline-entry.break')).toContainText('Lunch');
  const savedTimes = await page.locator('.timeline-time').evaluateAll(nodes => nodes.map(node => node.firstChild?.textContent ?? ''));
  expect(savedTimes).toEqual([...savedTimes].sort());
  await page.getByRole('button', { name: 'Start focus: Write feature', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Focus timer' })).toBeVisible();
  await page.clock.fastForward(90_000);
  await expect(page.getByRole('region', { name: 'Focus timer' }).locator('.timer')).toHaveText('01:30');
  await page.reload();
  await expect(page.getByRole('region', { name: 'Focus timer' }).locator('.timer')).toHaveText('01:30');
  await page.getByRole('region', { name: 'Focus timer' }).getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Focus timer' })).toContainText('Focus paused');
  await page.clock.fastForward(60_000);
  await expect(page.getByRole('region', { name: 'Focus timer' }).locator('.timer')).toHaveText('01:30');
  await page.getByRole('region', { name: 'Focus timer' }).getByRole('button', { name: '+30 min', exact: true }).click();
  await page.getByRole('button', { name: 'Reject plan', exact: true }).click();
  await expect(page.locator('.task').filter({ has: page.getByRole('heading', { name: 'Write feature', exact: true }) })).toContainText('180 min');
  await page.getByRole('region', { name: 'Focus timer' }).getByRole('button', { name: '+30 min', exact: true }).click();
  await page.getByRole('button', { name: 'Approve plan', exact: true }).click();
  await expect(page.locator('.task').filter({ has: page.getByRole('heading', { name: 'Write feature', exact: true }) })).toContainText('210 min');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Approve plan', exact: true })).toHaveCount(0);
  await page.screenshot({ path: 'test-results/planned-day.png', fullPage: true });
});
