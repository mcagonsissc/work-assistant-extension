import { test, expect } from '@playwright/test';
test('manual tasks persist through reload and support editing, completion, deferral and deletion', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  await page.getByLabel('Task title').fill('Review the onboarding PR');
  await page.getByLabel('Estimate · minutes').fill('45');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review the onboarding PR' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Review the onboarding PR' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Task title').fill('Review API');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await page.getByRole('button', { name: 'Complete Review API', exact: true }).click();
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', '1');
  await page.getByRole('button', { name: 'Reopen Review API', exact: true }).click();
  await page.getByRole('button', { name: 'Defer', exact: true }).click();
  await expect(page.locator('.metadata')).toContainText('Deferred');
  await page.getByRole('button', { name: 'Delete Review API', exact: true }).click();
  await page.getByRole('button', { name: 'Delete task', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review API' })).toHaveCount(0);
  expect(errors).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('theme and navigation persist; data export and confirmed clear work', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Add task', exact: true }).click();
  await page.getByLabel('Task title').fill('Export this task');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Switch to light theme' }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export local data' }).click();
  expect((await download).suggestedFilename()).toMatch(/^workday-.*\.json$/);
  await page.getByRole('button', { name: 'Delete all local data' }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Export this task' })).toBeVisible();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Delete all local data' }).click();
  await page.getByRole('button', { name: 'Delete permanently' }).click();
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Export this task' })).toHaveCount(0);
});
